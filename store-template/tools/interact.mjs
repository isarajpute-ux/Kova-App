import { chromium } from 'playwright-core';
const b = await chromium.launch({ args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8765/index.html', { waitUntil: 'networkidle' });
const t = s => p.locator(s).first().textContent();
const r = {};
r.atc0 = await t('[data-ag-atc-price]');
await p.locator('[data-ag-variant="5"]').click();
r.price_after_variant = await t('[data-ag-price]');
r.label = await t('[data-ag-vlabel]');
r.url = p.url();
r.atc1 = await t('[data-ag-atc-price]');
await p.locator('[data-ag-bundle]').nth(2).click();
r.qty = await p.locator('[data-ag-qty]').inputValue();
r.atc2 = await t('[data-ag-atc-price]');
r.bprices = await p.locator('[data-ag-bprice]').allTextContents();
r.id = await p.locator('[data-ag-id]').inputValue();
await p.locator('[data-ag-next]').click(); await p.waitForTimeout(600);
r.thumbActive = await p.locator('.agP__thumb.is-active').getAttribute('data-ag-thumb');
await p.locator('[data-mr-next]').click(); await p.waitForTimeout(600);
r.mrTransform = await p.locator('[data-mr-track]').evaluate(e => e.style.transform);
await p.locator('.agAcc__sum').first().click(); await p.waitForTimeout(400);
r.accOpen = await p.locator('.agAcc__item').first().evaluate(e => e.open);
await p.locator('[data-tab="1"]').click();
r.tabPanel = await p.locator('.agT__panel.is-active').getAttribute('data-panel');
await p.locator('[data-tab-next]').click();
r.tabPanel2 = await p.locator('.agT__panel.is-active').getAttribute('data-panel');
// sticky
await p.evaluate(() => window.scrollTo(0, 2600)); await p.waitForTimeout(700);
r.stickyOn = await p.locator('[data-ag-sticky]').evaluate(e => e.classList.contains('is-on'));
await p.evaluate(() => window.scrollTo(0, 0)); await p.waitForTimeout(700);
r.stickyOffTop = await p.locator('[data-ag-sticky]').evaluate(e => e.classList.contains('is-on'));
// before/after drag (mouse)
const fr = p.locator('[data-ag-ba]'); await fr.scrollIntoViewIfNeeded(); await p.waitForTimeout(2200);
const bb = await fr.boundingBox();
await p.mouse.move(bb.x + bb.width*0.5, bb.y + bb.height/2); await p.mouse.down(); await p.mouse.move(bb.x + bb.width*0.2, bb.y + bb.height/2, { steps: 5 }); await p.mouse.up();
r.baPos = await fr.evaluate(e => e.style.getPropertyValue('--pos'));
// countdown
r.clock = await p.locator('.agTop__clock').textContent();
await p.waitForTimeout(1200);
r.clock2 = await p.locator('.agTop__clock').textContent();
await p.locator('[data-top-close]').click();
r.topClosed = await p.locator('[data-ag-top]').evaluate(e => e.classList.contains('is-closed'));
r.eta = await t('[data-eta-left]') + ' | ' + await t('[data-eta-ship]') + ' | ' + await t('[data-eta-del]');
r.errs = errs;
console.log(JSON.stringify(r, null, 1));
await p.screenshot({ path: 'ba_after_drag.png' });
await b.close();
