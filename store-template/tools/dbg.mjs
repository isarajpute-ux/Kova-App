import { chromium } from 'playwright-core';
const b = await chromium.launch({ args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
await p.goto('http://localhost:8765/index.html', { waitUntil: 'networkidle' });
const r = {};
r.mrCount = await p.locator('[data-mr-track]').evaluate(e => e.children.length);
r.mrNextBox = await p.locator('[data-mr-next]').boundingBox();
r.hit = await p.evaluate(() => { const b = document.querySelector('[data-mr-next]').getBoundingClientRect(); const el = document.elementFromPoint(b.x + b.width/2, b.y + b.height/2); return el && (el.className.baseVal !== undefined ? 'svg:' + el.closest('button')?.className : el.className); });
await p.locator('[data-mr-next]').scrollIntoViewIfNeeded();
r.hit2 = await p.evaluate(() => { const b = document.querySelector('[data-mr-next]').getBoundingClientRect(); const el = document.elementFromPoint(b.x + b.width/2, b.y + b.height/2); return el ? (el.closest('button') ? el.closest('button').className : el.className) : null; });
await p.locator('[data-mr-next]').click();
await p.waitForTimeout(700);
r.tr = await p.locator('[data-mr-track]').evaluate(e => e.style.transform + ' / ' + getComputedStyle(e).transform);
r.atcTop = await p.locator('[data-ag-atc]').evaluate(e => e.getBoundingClientRect().top + window.scrollY);
r.docH = await p.evaluate(() => document.documentElement.scrollHeight);
await p.mouse.wheel(0, 2400); await p.waitForTimeout(900);
r.scrollY = await p.evaluate(() => window.scrollY);
r.sticky = await p.locator('[data-ag-sticky]').evaluate(e => e.className);
await b.close();
console.log(JSON.stringify(r, null, 1));
